def ev(anchors):
    result = []
    seen = set()
    for anchor in anchors:
        positions = [i + 1 for i, line in enumerate(lines) if anchor in line]
        if not positions:
            raise ValueError(anchor)
        for pos in positions:
            if (pos, anchor) not in seen:
                result.append({'line_start': pos, 'line_end': pos, 'quote': anchor})
                seen.add((pos, anchor))
    return sorted(result, key=lambda x: (x['line_start'], x['quote']))

