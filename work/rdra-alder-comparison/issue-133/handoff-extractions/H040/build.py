def ev(*quotes):
    result=[]
    for q in quotes:
        hits=[i+1 for i,s in enumerate(lines) if q in s]
        if not hits: raise ValueError(q)
        result.extend({'line_start':n,'line_end':n,'quote':q} for n in hits)
    return sorted(result,key=lambda x:(x['line_start'],x['quote']))
