import assert from 'node:assert/strict';
import {hiddenReadIndexes} from '../src/edge-visibility.ts';
const r=(kind,from,to,label='data')=>({kind,from,to,label});
const relations=[r('input','Object A','Activity A'),r('output','Activity A','Object A'),r('input','Object B','Activity A'),r('input','Object A','Activity B'),r('output','Activity B','Object C'),r('business-exception','Activity A','Activity B'),r('object-exception','Object A','Object B'),r('input','Object A','Activity A','second read'),r('output','Activity A','Object A','second write')];
const original=structuredClone(relations);
assert.deepEqual([...hiddenReadIndexes(relations,false)],[]);
assert.deepEqual([...hiddenReadIndexes(relations,true)],[0,7]);
assert.deepEqual(relations,original);
assert.deepEqual([...hiddenReadIndexes([],true)],[]);
assert.deepEqual([...hiddenReadIndexes([r('input','a|b','c'),r('output','b|c','a')],true)],[]);
assert.deepEqual([...hiddenReadIndexes([r('input','O','A'),r('business-exception','A','O')],true)],[]);
console.log('edge visibility: only paired Reads hidden; standalone Reads, all Writes, exceptions, stable indexes and source data preserved');
